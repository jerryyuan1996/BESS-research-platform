import {test,expect} from '@playwright/test';
import {mkdir} from 'node:fs/promises';
const screenshots='.tmp/italy-demo-research/screenshots';
test.beforeEach(async({page})=>{
  await page.route(/^https:\/\//,r=>r.abort());
  await page.addInitScript(()=>{localStorage.setItem('hub_lang','zh');localStorage.setItem('hub_lens','infraFund');});
});

test('Italy decision and financing explain the actual case with visible available assumptions',async({page},info)=>{
  await page.goto('/markets/italy');
  const decision=page.locator('#decision');
  await expect(decision.locator('.ic-case-identity')).toHaveAttribute('data-revenue-route','cap');
  await expect(decision).toContainText('100 MW / 400 MWh');
  await expect(decision).toContainText('4 小时');
  await expect(decision).toContainText('11.6%');
  await expect(decision).not.toContainText('既定下行');
  await expect(decision).not.toContainText('对价上限');
  await expect(decision.locator('.ix-decision-reasons')).toHaveCount(0);
  await expect(page.locator('#route-options')).toHaveCount(0);
  await expect(decision).toContainText('20% / 80%');
  const bankable=page.locator('#bankable');
  await expect(bankable.locator('.ic-bankable-case')).toBeVisible();
  await expect(bankable.locator('.ic-bankable-case details')).toHaveCount(0);
  await expect(bankable).toContainText('60.0%');await expect(bankable).toContainText('2.29×');
  await expect(bankable).toContainText('1.20×');await expect(bankable).toContainText('2.00×');
  await expect(bankable.locator('[data-debt-stream=cap]')).toContainText('18.5%');
  await expect(bankable.locator('[data-debt-stream=merchant]')).toContainText('41.5%');
  await expect(bankable).not.toContainText('未知');
  await expect(bankable.locator('.ic-bankable-kpis')).not.toContainText('Capex');
  await expect(bankable.locator('.ic-bankable-kpis')).not.toContainText('投资者目标回报');
  await mkdir(screenshots,{recursive:true});
  await decision.screenshot({path:`${screenshots}/${info.project.name}-decision.png`});
  await bankable.screenshot({path:`${screenshots}/${info.project.name}-bankable.png`});
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1);expect(overflow).toBe(false);
  await page.locator('.ix-language').click();
  await expect(page.locator('#decision')).toContainText('Capacity market + trading');
  await expect(page.locator('#bankable')).toContainText('Minimum annual DSCR');
});

