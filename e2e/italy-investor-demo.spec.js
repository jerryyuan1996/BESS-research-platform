test('selecting MACSE changes returns, cash flow and financing and survives language, reload and Back',async({page},info)=>{
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/markets/italy');
  const options=page.locator('#investment-options');
  const initialCash=await page.locator('#revenue').innerText();
  await options.locator('[data-play=it-ltda-6h]').click();
  await expect(page).toHaveURL(/play=it-ltda-6h/);
  await expect(page.locator('#decision .ic-case-identity')).toHaveAttribute('data-revenue-route','ltda');
  await expect(page.locator('#decision')).toContainText('600 MWh');
  await expect(page.locator('#decision')).toContainText('4.8%');
  const bankable=page.locator('#bankable');
  await expect(bankable).toContainText('1.33×');
  await expect(bankable.locator('[data-debt-stream=cap]')).toHaveCount(0);
  await expect(bankable.locator('[data-debt-stream=ltda]')).toContainText('49.0%');
  await expect(bankable.locator('[data-debt-stream=merchant]')).toContainText('10.8%');
  await expect(bankable.locator('.ic-debt-table tfoot')).toContainText('59.8%');
  expect(await page.locator('#revenue').innerText()).not.toEqual(initialCash);
  await mkdir(screenshots,{recursive:true});
  await bankable.screenshot({path:`${screenshots}/${info.project.name}-macse-financing.png`});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1)).toBe(false);
  await page.locator('.ix-language').click();
  await expect(page.locator('#decision')).toContainText('MACSE storage contract');
  await expect(options.locator('[data-play=it-ltda-6h]')).toHaveAttribute('aria-pressed','true');
  await page.reload();await expect(page.locator('#decision')).toContainText('600 MWh');
  await page.goBack();
  await expect(page.locator('#decision .ic-case-identity')).toHaveAttribute('data-revenue-route','cap');
  await expect(page.locator('#decision')).toContainText('11.6%');
  expect(errors).toEqual([]);
});

