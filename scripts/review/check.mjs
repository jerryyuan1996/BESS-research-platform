#!/usr/bin/env node
import { readFile } from 'node:fs/promises';
import path from 'node:path';
import { reviewProblems, REVIEW_SECTIONS } from '../../src/governance/review.js';
import { createViewStore } from '../view/writer.mjs';
import { briefingFromDisk } from '../../src/briefing/disk.js';
import { ROOT, hash, json, loadReview, atomicWrite, isMain, cliArgs, onlyOptions, validatePacketInputs, git, publicInputPath, updateDecisionLog, presentInputPaths, withReviewLock } from './common.mjs';
// Bind both the assistant's analysis and the generated engine figures. Decisions
// may update audit metadata, but cannot silently publish a modified impact.
export const reviewContentHash = review => hash(json({id:review.id,packetHash:review.packetHash,sections:review.sections,proposals:review.proposals,computed:review.computed}));
export async function changedInputs(root,packet){
  await validatePacketInputs(root,packet);
  const changed=[];
  const tracked=presentInputPaths(root);
  changed.push(...tracked.filter(file=>!(file in packet.manifest)));
  for(const [file,expected] of Object.entries(packet.manifest)){
    try {if(hash(await readFile(path.join(root,file)))!==expected)changed.push(file);}catch(e){if(e.code==='ENOENT')changed.push(file);else throw e;}
  }
  return changed;
}
export function analystChanges(proposals,id){
  return proposals.flatMap(p=>(p.changes??[]).map(c=>({...c,author:{kind:'analyst'},reason:[`${c.reason[0]} [Review ${id}; proposal ${p.id}]`,`${c.reason[1]} [复核 ${id}；建议 ${p.id}]`]})));
}
const project = b => ({lenses:b.lenses,plays:b.plays,grids:b.grids,queue:b.queue});
export async function calculateImpact({root,packet,proposals}){
  const now=new Date(packet.asOf);
  const baseline=await briefingFromDisk({root,now});
  const changes=analystChanges(proposals,packet.id);
  const proposed=await briefingFromDisk({root,now,overlay:changes});
  return {basis:'Existing briefing engine, in-memory view overlay only; not a changed model assumption.',asOf:packet.asOf,baseline:project(baseline),proposed:project(proposed)};
}
export function renderReport(review){
  const headings={A:'Observed evidence',B:'Investment interpretation',C:'Classified proposals',D:'Computed impact',E:'What would change the conclusion'};
  return `# Strategy review ${review.id}\n\nSnapshot: ${review.dataCommit}\n\n${REVIEW_SECTIONS.map(s=>`## ${s}. ${headings[s]}\n\n${review.sections[s]}${s==='D'?`\n\nFigures below are generated by review:check, not assistant-authored.\n\n\`\`\`json\n${json(review.computed)}\`\`\``:''}`).join('\n\n')}\n\n## Proposal decisions\n\n${(review.proposals??[]).map(p=>`- ${p.id} (${p.market}): ${p.classification}; ${review.decisions?.find(d=>d.proposal===p.id)?.decision??'awaiting decision'}`).join('\n')}\n`;
}
export async function validateReview({root=ROOT,packet,review,store=createViewStore(path.join(root,'view')),compute=calculateImpact,allowMovedData=false}){
  const errors=reviewProblems(review,packet);
  const refs=[...Object.values(review.sections??{}).join('\n').matchAll(/\[evidence:([^\]]+)\]/g)].map(m=>m[1]);
  if(!refs.length) errors.push('narrative must cite packet evidence with [evidence:<id>]');
  if(refs.some(r=>!packet.evidence.some(e=>e.id===r)))errors.push('section evidence reference does not resolve');
  if(/\d|%/.test(review.sections?.D??''))errors.push('section D narrative must not type figures; review:check generates figures');
  if(errors.length)throw new Error(errors.join('\n'));
  const moved=await changedInputs(root,packet);
  if(moved.length&&!allowMovedData)throw new Error(`packet inputs moved: ${moved.join(', ')}; prepare a fresh packet`);
  const changes=analystChanges(review.proposals.filter(p=>p.kind==='view'),review.id);
  await store.prepareBatch(changes,new Date(packet.asOf));
  const computed=await compute({root,packet,proposals:review.proposals.filter(p=>p.kind==='view')});
  return {computed,contentHash:reviewContentHash({...review,computed}),moved};
}
export async function checkReview({root=ROOT,id,...options}){
  return withReviewLock(root,async()=>{
  const {where,packet,review}=await loadReview(root,id);
  if(review.decisions?.length)throw new Error('review already has decisions; make a new review rather than rewriting its analysis');
  const checked=await validateReview({root,packet,review,...options});
  const result={...review,computed:checked.computed,checked:{contentHash:checked.contentHash,packetHash:packet.packetHash},status:review.proposals.length?'awaiting decision':'analysis complete'};
  await atomicWrite(path.join(where.dir,'review.json'),json(result));
  await atomicWrite(path.join(where.dir,'report.md'),renderReport(result));
  await updateDecisionLog(root,result);
  return result;
  });
}
if(isMain(import.meta.url)){
  try{const a=cliArgs(process.argv.slice(2));onlyOptions(a,[]);if(a._.length!==1)throw new Error('usage: review:check <id>');const r=await checkReview({id:a._[0]});console.log(`${r.id}: ${r.status}`);}catch(e){console.error(e.message);process.exitCode=1;}
}
