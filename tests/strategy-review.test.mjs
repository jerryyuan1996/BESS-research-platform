test('rehashing cannot forge committed inputs, dates, complete coverage or derived packet content',async t=>{
  const f=await fixture(t);
  const forge=async mutate=>{
    const packet=structuredClone(f.packet);await mutate(packet);
    delete packet.packetHash;packet.packetHash=hash(json(packet));
    f.review.packetHash=packet.packetHash;await f.save();
    await writeFile(f.where.packet,json(packet));
    await assert.rejects(checkReview({root:f.root,id:packet.id,compute:impact}),/Git snapshot/);
  };
  const file='public/data/public/wa-example.summary.json';
  const original=await readFile(path.join(f.root,file));
  await forge(async p=>{
    const dirty=json({datasetId:'wa-example',marketId:'wa',derived:{value:999}});
    await writeFile(path.join(f.root,file),dirty);p.manifest[file]=hash(dirty);
    p.evidence.find(e=>e.id===file).sha256=hash(dirty);
  });
  await writeFile(path.join(f.root,file),original);
  await forge(async p=>{
    const extra='src/untracked-audit.js';await mkdir(path.join(f.root,'src'),{recursive:true});
    await writeFile(path.join(f.root,extra),'export const evidence = 999;');
    p.manifest[extra]=hash('export const evidence = 999;');
    p.evidence.push({id:extra,kind:'dataset',sha256:p.manifest[extra]});
  });
  await forge(p=>{p.figures.engine.wa.base.holdIRR=999;});
  await forge(p=>{p.asOf='2026-11-09T00:00:00+00:00';});
  await forge(p=>{delete p.manifest[file];p.evidence=p.evidence.filter(e=>e.id!==file);});
  await forge(p=>{p.dataCommit=p.dataCommit.slice(0,12);});
  await forge(p=>{p.baselines.wa.latestChangelogId='invented';});
  await forge(p=>{p.rules=[];p.policySinceBaseline.wa=['invented'];});
  assert.equal(await readFile(path.join(f.root,'view/changelog.jsonl'),'utf8'),'');
});
